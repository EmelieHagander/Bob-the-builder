/** Publish the new capability on existing tools; no additional runtime agent. */
import { readFileSync, writeFileSync } from 'node:fs'
import { PROJECT_EDIT_TOOLS } from '../supabase/functions/_shared/project-edits.ts'
const method = 'For uncertain physical form, agree geometry cheaply before detailed construction: use a Solution design_intent.model and its deterministic plan/profile or named principle section. Read its current edit context, preserve feature and choice links, make bounded corrections, and reopen the saved version and reported gaps. Select the exact Solution through existing target decisions when the direction is settled. Concept dimensions remain decisions, estimates or unknowns; no Building or measured fact is created. Construction retains these identities and dimensions through existing Artifact lineage, K2 and independent CAD review. This first slice maps unrotated boxes exactly; unsupported shapes/subdivision remain explicit. A sketch is useful when it resolves uncertainty, not a compulsory phase or approval for every edit.'
const workflow = { name: 'workflow_solution_concept', card: 'Explore and correct early 2D geometry on a Solution before detailed construction.', method,
  tools: ['read_project_edit_context', 'edit_project_record', 'read_solution_context', 'create_solution_alternative', 'select_solution_alternative'] }
const description = PROJECT_EDIT_TOOLS[1].function.description
const sql = `-- Generated by scripts/build-ai-form-concept-catalog.ts.
-- Apply concept core, deploy matching ask-bob AND bob-worker, then publish.
begin;
do $form_publication$
declare prior shared.ai_prompt_versions; definition jsonb; key text; next_version integer; vid uuid; activation jsonb:='{}';
 workflow jsonb:=$form_workflow$${JSON.stringify(workflow)}$form_workflow$::jsonb;
 description text:=$form_description$${description}$form_description$;
begin
 perform pg_advisory_xact_lock(hashtextextended('ai_catalog:bob',0));
 if to_regprocedure('bob_private.solution_concept_result(jsonb)') is null then raise exception 'concept_core_required'; end if;
 foreach key in array array['tools.edit_project_record','bob.workflows'] loop
  select v.* into prior from shared.ai_prompts p join shared.ai_prompt_versions v on v.id=p.active_version_id where p.app='bob' and p.prompt_key=key for update of p;
  if not found then raise exception 'concept_catalog_dependency_missing'; end if;
  definition:=prior.definition;
  if key='tools.edit_project_record' then
   definition:=jsonb_set(definition,'{description}',to_jsonb(description));
  else
   if exists(select 1 from jsonb_array_elements(definition->'workflows') w where w->>'name'=workflow->>'name') then raise exception 'concept_method_already_exists'; end if;
   definition:=jsonb_set(definition,'{workflows}',definition->'workflows'||jsonb_build_array(workflow));
  end if;
  select coalesce(max(version),0)+1 into next_version from shared.ai_prompt_versions where prompt_id=prior.prompt_id;
  insert into shared.ai_prompt_versions(prompt_id,version,definition_kind,definition_format_version,metadata,content,definition,flow,available_variables)
   values(prior.prompt_id,next_version,prior.definition_kind,prior.definition_format_version,(prior.metadata-'seed_version'-'source_revision')||jsonb_build_object('publication','form-concept-v1'),prior.content,definition,prior.flow,prior.available_variables) returning id into vid;
  activation:=activation||jsonb_build_object(key,vid);
 end loop;
 perform shared.activate_ai_catalog('bob',activation);
end $form_publication$;
commit;
`
const target = process.argv.find(arg => arg.endsWith('_ai_form_concept_catalog.sql'))
if (!target) throw new Error('Pass the new *_ai_form_concept_catalog.sql migration path')
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== sql) throw new Error('FORM publication differs from executable contracts')
  console.log('FORM catalog matches the executable tool and method.')
} else writeFileSync(target, sql)
