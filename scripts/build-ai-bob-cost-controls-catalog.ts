/** Publish the owner-approved small bench and medium reasoning profile.
 * All tool text/schema bindings remain in the immutable catalog. */
import { readFileSync, writeFileSync } from 'node:fs'
import { CONSTRUCTION_PARAMETER_REFRESH_TOOL, CONSTRUCTION_SOURCE_REFRESH_NOTE } from '../supabase/functions/_shared/construction-draft.ts'

const spec = {
 core_tools: ['describe_tool', 'search_project_data', 'open_project_item', 'read_solution_context', 'read_construction_draft', 'change_construction_parameters'],
 reasoning_effort: 'medium',
 target_revision: CONSTRUCTION_PARAMETER_REFRESH_TOOL.function.parameters.properties.target_revision,
 note: CONSTRUCTION_SOURCE_REFRESH_NOTE,
}
const sql = `-- Generated by scripts/build-ai-bob-cost-controls-catalog.ts.
-- Install the source-refresh migration and both compatible Edge runtimes first.
begin;
do $cost_controls_publication$
declare spec jsonb:=$bob_cost_controls_spec$${JSON.stringify(spec)}$bob_cost_controls_spec$::jsonb;
 key text; prior shared.ai_prompt_versions; definition jsonb; metadata jsonb; next_version integer; version_uuid uuid; activation jsonb:='{}';
begin
 perform pg_advisory_xact_lock(hashtextextended('ai_catalog:bob',0));
 if not exists(select 1 from shared.ai_prompts p join shared.ai_prompt_versions v on v.id=p.active_version_id
  where p.app='bob' and p.prompt_key='tier.standard' and v.definition->>'model_name'='gpt-5.4') then raise exception 'bob_model_binding_changed'; end if;
 foreach key in array array['tools.change_construction_parameters','bob.tools','profile.ask-bob'] loop
  select v.* into prior from shared.ai_prompts p join shared.ai_prompt_versions v on v.id=p.active_version_id
   where p.app='bob' and p.prompt_key=key and p.retired_at is null for update of p;
  if not found then raise exception 'bob_cost_contract_missing: %',key; end if;
  if prior.metadata->>'bob_cost_controls_version'='1' then continue; end if;
  definition:=prior.definition;
  metadata:=(prior.metadata-'seed_version'-'source_revision')||jsonb_build_object('publication','bob-cost-controls-v1','bob_cost_controls_version',1);
  if key='tools.change_construction_parameters' then
   definition:=jsonb_set(definition,'{parameters,properties,target_revision}',spec->'target_revision');
   definition:=jsonb_set(definition,'{parameters,properties,changes,minItems}','0');
   definition:=jsonb_set(definition,'{parameters,required}',(definition#>'{parameters,required}')||jsonb_build_array('target_revision'));
   definition:=jsonb_set(definition,'{required_parameters}',definition#>'{parameters,required}');
   definition:=jsonb_set(definition,'{description}',to_jsonb((definition->>'description')||(spec->>'note')));
   metadata:=metadata||jsonb_build_object('construction_source_refresh_version',1);
  elsif key='bob.tools' then
   definition:=jsonb_set(definition,'{core_tools}',spec->'core_tools');
  else
   if definition->>'tier'<>'standard' then raise exception 'bob_profile_tier_changed'; end if;
   definition:=jsonb_set(definition,'{reasoning_effort}',spec->'reasoning_effort');
  end if;
  select coalesce(max(version),0)+1 into next_version from shared.ai_prompt_versions where prompt_id=prior.prompt_id;
  insert into shared.ai_prompt_versions(prompt_id,version,definition_kind,definition_format_version,metadata,content,definition,flow,available_variables)
   values(prior.prompt_id,next_version,prior.definition_kind,prior.definition_format_version,metadata,prior.content,definition,prior.flow,prior.available_variables) returning id into version_uuid;
  activation:=activation||jsonb_build_object(key,version_uuid);
 end loop;
 if activation<>'{}'::jsonb then perform shared.activate_ai_catalog('bob',activation); end if;
end $cost_controls_publication$;
commit;
`
const target = process.argv.find(arg => arg.endsWith('_ai_bob_cost_controls_catalog.sql'))
if (!target) throw Error('Pass the *_ai_bob_cost_controls_catalog.sql migration path')
if (process.argv.includes('--check')) {
 if (readFileSync(target, 'utf8') !== sql) throw Error('Bob cost controls publication is stale')
} else writeFileSync(target, sql)
