/** Owner decision 2026-10-29 ("Bob ska ha det han behöver när han behöver det"):
 * pin result window version 2 on the main Bob contract. An older read repeated
 * later leaves the window first and the latest result per record stays whole,
 * under the unchanged 20,000-token ceiling. Pinned manifests keep version 1. */
import { readFileSync, writeFileSync } from 'node:fs'

const spec = { key: 'agent-contract.ask-bob', requires: { result_reference_version: 1 }, metadata: { result_window_version: 2 } }

const sql = `-- Generated by scripts/build-bob-result-window-catalog.ts.
-- Owner decision 2026-10-29: superseded repeat reads leave Bob's result window
-- first and the latest result per record stays whole, under the unchanged
-- token ceiling. Install both Bob runtimes with the result_window_version 2
-- consumer before activation. Pinned manifests and running jobs keep version 1.
begin;
set local lock_timeout='5s';
set local statement_timeout='60s';
do $result_window_publication$
declare spec jsonb:=$result_window_spec$${JSON.stringify(spec)}$result_window_spec$::jsonb;
 prior shared.ai_prompt_versions; next_version integer; version_uuid uuid;
begin
 perform pg_advisory_xact_lock(hashtextextended('ai_catalog:bob',0));
 select v.* into prior from shared.ai_prompts p join shared.ai_prompt_versions v on v.id=p.active_version_id
  where p.app='bob' and p.prompt_key=spec->>'key' and p.retired_at is null for update of p;
 if not found then raise exception 'result_window_contract_missing'; end if;
 if prior.metadata->>'result_window_version'='2' then return; end if;
 if not prior.metadata@>(spec->'requires') then raise exception 'result_window_requires_result_references'; end if;
 select coalesce(max(version),0)+1 into next_version from shared.ai_prompt_versions where prompt_id=prior.prompt_id;
 insert into shared.ai_prompt_versions(prompt_id,version,definition_kind,definition_format_version,metadata,content,definition,flow,available_variables)
  values(prior.prompt_id,next_version,prior.definition_kind,prior.definition_format_version,
   (prior.metadata-'seed_version'-'source_revision')||(spec->'metadata')||jsonb_build_object('publication','bob-result-window-v2'),
   prior.content,prior.definition,prior.flow,prior.available_variables) returning id into version_uuid;
 perform shared.activate_ai_catalog('bob',jsonb_build_object(spec->>'key',version_uuid));
end $result_window_publication$;
commit;
`
const target = process.argv.find(arg => arg.endsWith('_bob_result_window_catalog.sql'))
if (target) {
  if (process.argv.includes('--check')) { if (readFileSync(target, 'utf8') !== sql) throw Error('Result window publication is stale') }
  else writeFileSync(target, sql)
} else if (process.argv[1]?.endsWith('build-bob-result-window-catalog.ts')) throw Error('Pass the *_bob_result_window_catalog.sql migration path')
