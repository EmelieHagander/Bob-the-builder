/** Publish read_building_scope and change_building_scope without replacing live catalog customizations. */
import { readFileSync, writeFileSync } from 'node:fs'
import { BUILDING_SCOPE_TOOLS } from '../supabase/functions/_shared/project-building-scope.ts'
const names = BUILDING_SCOPE_TOOLS.map(t => t.function.name)
const contracts = BUILDING_SCOPE_TOOLS.map(t => t.function)
const policies = JSON.parse(readFileSync('supabase/functions/_shared/project-tools/catalog-seed.json', 'utf8')).filter((r: any) => names.includes(r.name))
if (policies.length !== names.length) throw new Error('Seed policies for the building scope tools are missing')
// The save_building_context manual pointed to manual linking; Bob can now link an existing Building himself.
const manual = { from: 'Existing unscoped Buildings require explicit manual linking;', to: 'Link an existing Building with change_building_scope before recording context there;' }
const workflow = {
  name: 'workflow_facts_and_site',
  card: 'Link the project to its building and rooms; record measurements, building and site facts, stairs, room layouts and building plans with their sources.',
  method: ' A project concerns a real building: find it among the owner\'s buildings, link it once the owner has identified it, and mark the rooms and Area mappings the work covers. Linking shares the whole building with every project member, so say what became visible.',
}
const sql = `-- Generated by scripts/build-ai-building-scope-catalog.ts.
-- Apply 20261025133000_project_room_scope.sql and 20261025150000_bob_building_scope.sql,
-- deploy ask-bob AND bob-worker from the same source, then activate this publication.
begin;
do $building_scope_publication$
declare contracts jsonb:=$building_scope_contracts$${JSON.stringify(contracts, null, 2)}$building_scope_contracts$::jsonb;
 policies jsonb:=$building_scope_policies$${JSON.stringify(policies, null, 2)}$building_scope_policies$::jsonb;
 manual jsonb:=$building_scope_manual$${JSON.stringify(manual)}$building_scope_manual$::jsonb;
 workflow jsonb:=$building_scope_workflow$${JSON.stringify(workflow)}$building_scope_workflow$::jsonb;
 patch jsonb; policy jsonb; prior shared.ai_prompt_versions; template shared.ai_prompt_versions;
 prompt_uuid uuid; version_uuid uuid; next_version integer; definition jsonb; activation jsonb:='{}'; key text;
begin
 perform pg_advisory_xact_lock(hashtextextended('ai_catalog:bob',0));
 select v.* into template from shared.ai_prompts p join shared.ai_prompt_versions v on v.id=p.active_version_id where p.app='bob' and p.prompt_key='tools.read_plan_link_context';
 if not found then raise exception 'building_scope_template_missing'; end if;
 for patch in select value from jsonb_array_elements(contracts) loop
  select value into policy from jsonb_array_elements(policies) where value->>'name'=patch->>'name';
  if exists(select 1 from shared.ai_prompts where app='bob' and prompt_key='tools.'||(patch->>'name')) then raise exception 'building_scope_contract_exists'; end if;
  insert into shared.ai_prompts(app,prompt_key,label,description,content,flow,definition_kind)
   values('bob','tools.'||(patch->>'name'),policy->>'description',policy->>'description','','','tool_contract') returning id into prompt_uuid;
  definition:=template.definition||patch||jsonb_build_object('handler',patch->>'name','required_parameters',patch#>'{parameters,required}','optional_parameters','[]'::jsonb,
   'card_description',policy->>'description','additional_description',policy->>'how_to');
  insert into shared.ai_prompt_versions(prompt_id,version,definition_kind,definition_format_version,metadata,content,definition,flow,available_variables)
   values(prompt_uuid,1,'tool_contract',1,jsonb_build_object('publication','building-scope-v1','server_fields',case when (patch#>'{parameters,required}')?'request_quote' then '["request_quote"]'::jsonb else '[]'::jsonb end),
    template.content,definition,template.flow,template.available_variables) returning id into version_uuid;
  activation:=activation||jsonb_build_object('tools.'||(patch->>'name'),version_uuid);
 end loop;
 for key in select unnest(array['tools.save_building_context','bob.tools','bob.workflows']) loop
  select v.* into prior from shared.ai_prompts p join shared.ai_prompt_versions v on v.id=p.active_version_id where p.app='bob' and p.prompt_key=key for update of p;
  if not found then raise exception 'building_scope_dependency_missing'; end if;
  definition:=prior.definition;
  if key='tools.save_building_context' then
   if position(manual->>'from' in coalesce(definition->>'additional_description',''))=0 then raise exception 'building_scope_manual_changed'; end if;
   definition:=jsonb_set(definition,'{additional_description}',to_jsonb(replace(definition->>'additional_description',manual->>'from',manual->>'to')));
  elsif key='bob.tools' then
   for policy in select value from jsonb_array_elements(policies) loop
    definition:=jsonb_set(definition,'{catalog}',definition->'catalog'||jsonb_build_array(policy));
    definition:=jsonb_set(definition,'{contract_keys}',definition->'contract_keys'||jsonb_build_array('tools.'||(policy->>'name')));
   end loop;
   if not exists(select 1 from jsonb_array_elements(definition->'shelves') s where s->>'label'='Building and site') then raise exception 'building_scope_shelf_missing'; end if;
   definition:=jsonb_set(definition,'{shelves}',(select jsonb_agg(case when s->>'label'='Building and site' then jsonb_set(s,'{tools}',(select jsonb_agg(c->>'name' order by i) from jsonb_array_elements(contracts) with ordinality y(c,i))||(s->'tools')) else s end order by n) from jsonb_array_elements(definition->'shelves') with ordinality x(s,n)));
  else
   if not exists(select 1 from jsonb_array_elements(definition->'workflows') w where w->>'name'=workflow->>'name') then raise exception 'building_scope_workflow_missing'; end if;
   definition:=jsonb_set(definition,'{workflows}',(select jsonb_agg(case when w->>'name'=workflow->>'name' then w||jsonb_build_object('card',workflow->>'card','tools',(w->'tools')||(select jsonb_agg(c->>'name' order by i) from jsonb_array_elements(contracts) with ordinality y(c,i)),'method',(w->>'method')||(workflow->>'method')) else w end order by n) from jsonb_array_elements(definition->'workflows') with ordinality x(w,n)));
  end if;
  select coalesce(max(version),0)+1 into next_version from shared.ai_prompt_versions where prompt_id=prior.prompt_id;
  insert into shared.ai_prompt_versions(prompt_id,version,definition_kind,definition_format_version,metadata,content,definition,flow,available_variables)
   values(prior.prompt_id,next_version,prior.definition_kind,prior.definition_format_version,(prior.metadata-'seed_version'-'source_revision')||jsonb_build_object('publication','building-scope-v1'),prior.content,definition,prior.flow,prior.available_variables) returning id into version_uuid;
  activation:=activation||jsonb_build_object(key,version_uuid);
 end loop;
 for policy in select value from jsonb_array_elements(policies) loop
  insert into bob.tool_catalog(name,description,how_to,schema_version,always_load,preload_phases,active)
   values(policy->>'name',policy->>'description',policy->>'how_to',(policy->>'schema_version')::integer,false,array[]::text[],true);
 end loop;
 perform shared.activate_ai_catalog('bob',activation);
end $building_scope_publication$;
commit;
`
const target = process.argv.find(arg => arg.endsWith('_ai_building_scope_catalog.sql'))
if (!target) throw new Error('Pass the *_ai_building_scope_catalog.sql migration path')
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== sql) throw new Error('Building scope publication differs from executable tools')
  console.log('Building scope catalog matches executable tools')
} else writeFileSync(target, sql)
