/** Owner decision 2026-10-29: a reviewed starting list of standard materials,
 * sizes and combinations, generated from scripts/data/standard-materials.json.
 * Combinations become shared catalog material definitions through the same
 * normalization and identity rules as Bob's own definitions. Weight stays null. */
import { readFileSync, writeFileSync } from 'node:fs'

type Material = { key: string; name: string; category: string; aliases: string[] }
type Size = { key: string; form: string; label: string | null; length_mm: number | null; width_mm: number | null; depth_mm: number | null; aliases: string[] }
type Combination = { material: string; size: string | null; unit: string; form?: string }
export type StandardMaterials = { note: string; materials: Material[]; sizes: Size[]; combinations: Combination[] }

const KEY = /^[a-z][a-z0-9_]{0,63}$/
const FORMS = ['sheet', 'rectangular_profile', 'fastener', 'roll', 'piece']
const UNITS = ['pcs', 'm', 'm2', 'm3', 'kg', 'l']
const fail = (message: string): never => { throw Error('standard_materials: ' + message) }

/** Rejects a list the SQL seed could only partly apply. */
export function validateStandardMaterials(data: StandardMaterials): StandardMaterials {
  const unique = (keys: string[], what: string) => { if (new Set(keys).size !== keys.length) fail('duplicate ' + what) }
  unique(data.materials.map(m => m.key), 'material key'); unique(data.sizes.map(s => s.key), 'size key')
  unique(data.materials.map(m => m.name.toLowerCase().trim()), 'material name')
  for (const m of data.materials) {
    if (!KEY.test(m.key) || !m.name?.trim() || m.name.length > 200 || !/^[a-z][a-z0-9_.]{0,63}$/.test(m.category ?? '')) fail('material ' + m.key)
    if (!Array.isArray(m.aliases) || m.aliases.some(a => !a.trim() || a.length > 120)) fail('aliases of ' + m.key)
  }
  for (const s of data.sizes) {
    if (!KEY.test(s.key) || !FORMS.includes(s.form) || (s.label !== null && (!s.label.trim() || s.label.length > 120))) fail('size ' + s.key)
    for (const v of [s.length_mm, s.width_mm, s.depth_mm]) if (v !== null && !(Number.isFinite(v) && v > 0 && v <= 1_000_000)) fail('dimension of ' + s.key)
    if (!Array.isArray(s.aliases) || s.aliases.some(a => !a.trim() || a.length > 120)) fail('aliases of ' + s.key)
  }
  unique(data.combinations.map(c => c.material + '|' + (c.size ?? '')), 'combination')
  for (const c of data.combinations) {
    if (!data.materials.some(m => m.key === c.material)) fail('unknown material ' + c.material)
    if (c.size !== null && !data.sizes.some(s => s.key === c.size)) fail('unknown size ' + c.size)
    if (!UNITS.includes(c.unit)) fail('unit of ' + c.material)
    if (c.size === null ? !FORMS.includes(c.form ?? '') : c.form !== undefined) fail('form of ' + c.material)
  }
  return data
}

export function standardMaterialsSeedSql(data: StandardMaterials): string {
  validateStandardMaterials(data)
  const aliases = data.materials.reduce((n, m) => n + m.aliases.length, 0) + data.sizes.reduce((n, s) => n + s.aliases.length, 0)
  return `-- Generated by scripts/build-standard-materials-seed.ts from scripts/data/standard-materials.json.
-- Starting list for owner review (2026-10-29): ${data.materials.length} materials, ${data.sizes.length} sizes, ${data.combinations.length} combinations, ${aliases} aliases.
-- Generic specifications only: no product, supplier, price or weight. Re-applying changes nothing.
begin;
set local lock_timeout='5s';
set local statement_timeout='60s';
do $standard_materials_seed$
declare spec jsonb:=$standard_materials$${JSON.stringify(data)}$standard_materials$::jsonb;
 m jsonb; s jsonb; c jsonb; v_alias text; mt bob.material_types; sz bob.material_sizes; v_form text; v_profile text; props jsonb;
 normalized jsonb; cats text[]; identity_doc jsonb; fingerprint text; item uuid; v_name text; v_notes text;
begin
 perform pg_advisory_xact_lock(hashtextextended('bob:catalog:',0));
 for m in select value from jsonb_array_elements(spec->'materials') loop
  insert into bob.material_types(name,category_code,review_status,seed_key) values(m->>'name',m->>'category','reviewed',m->>'key') on conflict do nothing;
  select * into mt from bob.material_types t where t.seed_key=m->>'key' or lower(btrim(t.name))=lower(btrim(m->>'name')) order by t.seed_key nulls last limit 1;
  for v_alias in select jsonb_array_elements_text(m->'aliases') loop
   insert into bob.material_aliases(alias,material_type_id,review_status) values(v_alias,mt.id,'reviewed') on conflict do nothing;
  end loop;
 end loop;
 for s in select value from jsonb_array_elements(spec->'sizes') loop
  insert into bob.material_sizes(label,form_code,length_mm,width_mm,depth_mm,review_status,seed_key)
   values(s->>'label',s->>'form',(s->>'length_mm')::numeric,(s->>'width_mm')::numeric,(s->>'depth_mm')::numeric,'reviewed',s->>'key') on conflict do nothing;
  select * into sz from bob.material_sizes where seed_key=s->>'key';
  for v_alias in select jsonb_array_elements_text(s->'aliases') loop
   insert into bob.material_aliases(alias,material_size_id,review_status) values(v_alias,sz.id,'reviewed') on conflict do nothing;
  end loop;
 end loop;
 for c in select value from jsonb_array_elements(spec->'combinations') loop
  select * into mt from bob.material_types where seed_key=c->>'material';
  sz:=null;
  if c->>'size' is not null then select * into sz from bob.material_sizes where seed_key=c->>'size'; end if;
  if mt.id is null or (c->>'size' is not null and sz.id is null) or mt.category_code is null then raise exception 'standard_materials_reference:%',c; end if;
  continue when exists(select 1 from bob.catalog_items i where i.project_id is null and i.material_type_id=mt.id and i.material_size_id is not distinct from sz.id);
  v_form:=coalesce(sz.form_code,c->>'form');
  v_profile:=case v_form when 'sheet' then 'sheet_stock' when 'rectangular_profile' then 'rectangular_profile' when 'fastener' then 'fastener'
   when 'roll' then 'roll_stock' when 'piece' then 'piece' end;
  if v_profile is null then raise exception 'standard_materials_form:%',c; end if;
  -- Known dimensions are declared specifications; a required unknown stays unknown.
  props:=case v_profile
   when 'sheet_stock' then jsonb_build_object('thickness',bob_private.seed_length(sz.depth_mm,'Tjocklek anges inte i startlistan.'))
   when 'rectangular_profile' then jsonb_build_object('thickness',bob_private.seed_length(sz.depth_mm,'Tjocklek anges inte i startlistan.'),
    'width',bob_private.seed_length(sz.width_mm,'Bredd anges inte i startlistan.'))
   when 'fastener' then jsonb_build_object('diameter',bob_private.seed_length(sz.width_mm,'Diameter anges inte i startlistan.'),
    'length',bob_private.seed_length(sz.length_mm,'Längd anges inte i startlistan.'))
   else '{}'::jsonb end;
  if sz.label is not null and v_profile in ('sheet_stock','rectangular_profile') then
   props:=props||jsonb_build_object('nominal_size',jsonb_build_object('value',sz.label,'unit',null,'truth','provided_spec','parameter',null,'note','Standardmått i startlistan.'));
  end if;
  select array_agg(x order by x) into cats from unnest(array[mt.category_code,v_form]) x;
  normalized:=bob_private.catalog_normalize(v_profile,1,props,'material');
  v_name:=mt.name||coalesce(' '||sz.label,'');
  v_notes:='Standardmaterial från startlistan: '||mt.name||'. Generisk specifikation; produkt, kvalitet och vikt är inte verifierade.';
  identity_doc:=jsonb_build_object('version',1,'kind','material','profile_code',v_profile,'profile_revision',1,
   'categories',cats,'properties',normalized->'properties','material_id',null,'material_revision',null,'notes',v_notes);
  fingerprint:=case when (normalized->>'has_unknown')::boolean then null else md5(identity_doc::text) end;
  item:=gen_random_uuid();
  insert into bob.catalog_items(id,project_id,kind,current_revision,identity_hash,material_type_id,material_size_id,unit_code,review_status)
   values(item,null,'material',1,fingerprint,mt.id,sz.id,c->>'unit','reviewed');
  insert into bob.catalog_item_revisions(item_id,revision,name,aliases,profile_code,profile_revision,properties,material_id,material_revision,notes,has_unknown,parameter_keys,identity_document,source_kind)
   values(item,1,v_name,'{}',v_profile,1,normalized->'properties',null,null,v_notes,(normalized->>'has_unknown')::boolean,
    array(select jsonb_array_elements_text(normalized->'parameter_keys')),identity_doc,'seed');
  insert into bob.catalog_item_categories select item,1,x from unnest(cats) x;
 end loop;
end $standard_materials_seed$;
commit;
`
}

const source = new URL('./data/standard-materials.json', import.meta.url)
const target = process.argv.find(arg => arg.endsWith('_standard_materials_seed.sql'))
if (target) {
  const sql = standardMaterialsSeedSql(JSON.parse(readFileSync(source, 'utf8')))
  if (process.argv.includes('--check')) { if (readFileSync(target, 'utf8') !== sql) throw Error('Standard materials seed is stale') }
  else writeFileSync(target, sql)
} else if (process.argv[1]?.endsWith('build-standard-materials-seed.ts')) throw Error('Pass the *_standard_materials_seed.sql migration path')
