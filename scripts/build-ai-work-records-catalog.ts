/** Add the server-bound work records without replacing live catalog customizations. */
import { readFileSync, writeFileSync } from 'node:fs'
import { WORK_RECORD_TOOLS as PROJECT_EDIT_TOOLS } from '../supabase/functions/_shared/project-work-records.ts'
const names = PROJECT_EDIT_TOOLS.map(t => t.function.name)
const contracts = PROJECT_EDIT_TOOLS.map(t => t.function)
const policies = JSON.parse(readFileSync('supabase/functions/_shared/project-tools/catalog-seed.json','utf8')).filter((r: any) => names.includes(r.name))
const append = ['save_project_area','save_project_task','save_project_measurement','archive_project_measurement','update_project_task_work','save_project_build_day','delete_project_task','delete_project_build_day','archive_project_area','set_project_phase','update_project_schedule','delete_shopping_item','manage_task_readiness'].map(name => ({key:'tools.'+name,text:' Superseded for fresh manifests by read_work_context and explicit edit_work_record/create_work_record/change_work_relation/change_work_state. Runtime binds identity, exact snapshot, scope and preserved data.'}))

const sql = `-- Generated by scripts/build-ai-work-records-catalog.ts.
-- Apply core first, deploy ask-bob AND bob-worker, then activate this publication.
begin;
do $server_bound_edits_catalog$
declare contracts jsonb:=$bound_edit_contracts$${JSON.stringify(contracts,null,2)}$bound_edit_contracts$::jsonb;
 policies jsonb:=$bound_edit_policies$${JSON.stringify(policies,null,2)}$bound_edit_policies$::jsonb;
 append jsonb:=$bound_edit_append$${JSON.stringify(append,null,2)}$bound_edit_append$::jsonb;
 patch jsonb; policy jsonb; prior shared.ai_prompt_versions; template shared.ai_prompt_versions;
 prompt_uuid uuid; version_uuid uuid; next_version integer; definition jsonb; activation jsonb:='{}';
begin
 perform pg_advisory_xact_lock(hashtextextended('ai_catalog:bob',0));
 select v.* into template from shared.ai_prompts p join shared.ai_prompt_versions v on v.id=p.active_version_id where p.app='bob' and p.prompt_key='tools.save_project_description';
 if not found then raise exception 'bound_edit_template_missing'; end if;
 for patch in select value from jsonb_array_elements(contracts) loop
  select value into policy from jsonb_array_elements(policies) where value->>'name'=patch->>'name';
  select v.* into prior from shared.ai_prompts p join shared.ai_prompt_versions v on v.id=p.active_version_id where p.app='bob' and p.prompt_key='tools.'||(patch->>'name');
  if not found then
   insert into shared.ai_prompts(app,prompt_key,label,description,content,flow,definition_kind)
    values('bob','tools.'||(patch->>'name'),policy->>'description',policy->>'description','','','tool_contract') returning id into prompt_uuid;
   prior:=template;
  else prompt_uuid:=prior.prompt_id;
  end if;
  definition:=prior.definition||patch||jsonb_build_object('handler',patch->>'name','required_parameters',patch#>'{parameters,required}','optional_parameters','[]'::jsonb,'additional_description',policy->>'how_to');
  definition:=jsonb_set(definition,'{envelope,schema_version}','1'::jsonb);
  select coalesce(max(version),0)+1 into next_version from shared.ai_prompt_versions where prompt_id=prompt_uuid;
  insert into shared.ai_prompt_versions(prompt_id,version,definition_kind,definition_format_version,metadata,content,definition,flow,available_variables)
   values(prompt_uuid,next_version,'tool_contract',1,jsonb_build_object('publication','server-bound-work-records','server_fields',case when patch->>'name'<>'read_work_context' then ' ["request_quote"]'::jsonb else '[]'::jsonb end),prior.content,definition,prior.flow,prior.available_variables) returning id into version_uuid;
  activation:=activation||jsonb_build_object('tools.'||(patch->>'name'),version_uuid);
 end loop;
 for patch in select value from jsonb_array_elements(append) loop
  select v.* into prior from shared.ai_prompts p join shared.ai_prompt_versions v on v.id=p.active_version_id where p.app='bob' and p.prompt_key=patch->>'key';
  if not found then raise exception 'bound_edit_legacy_contract_missing'; end if;
  definition:=jsonb_set(prior.definition,'{additional_description}',to_jsonb(coalesce(prior.definition->>'additional_description','')||(patch->>'text')));
  select coalesce(max(version),0)+1 into next_version from shared.ai_prompt_versions where prompt_id=prior.prompt_id;
  insert into shared.ai_prompt_versions(prompt_id,version,definition_kind,definition_format_version,metadata,content,definition,flow,available_variables)
   values(prior.prompt_id,next_version,prior.definition_kind,prior.definition_format_version,(prior.metadata-'seed_version'-'source_revision')||jsonb_build_object('publication','server-bound-work-records'),prior.content,definition,prior.flow,prior.available_variables) returning id into version_uuid;
  activation:=activation||jsonb_build_object(patch->>'key',version_uuid);
 end loop;
 select v.* into prior from shared.ai_prompts p join shared.ai_prompt_versions v on v.id=p.active_version_id where p.app='bob' and p.prompt_key='bob.tools' for update of p;
 if not found then raise exception 'bound_edit_toolbox_missing'; end if;
 definition:=prior.definition;
 for policy in select value from jsonb_array_elements(policies) loop
  insert into bob.tool_catalog(name,description,how_to,schema_version,always_load,preload_phases,active)
   values(policy->>'name',policy->>'description',policy->>'how_to',(policy->>'schema_version')::integer,(policy->>'always_load')::boolean,array(select jsonb_array_elements_text(policy->'preload_phases')),(policy->>'active')::boolean)
   on conflict(name) do nothing;
  if not exists(select 1 from jsonb_array_elements(definition->'catalog') r where r->>'name'=policy->>'name') then
   definition:=jsonb_set(definition,'{catalog}',definition->'catalog'||jsonb_build_array(policy));
  end if;
  if not definition->'contract_keys'?('tools.'||(policy->>'name')) then
   definition:=jsonb_set(definition,'{contract_keys}',definition->'contract_keys'||jsonb_build_array('tools.'||(policy->>'name')));
  end if;
  definition:=jsonb_set(definition,'{shelves}',(select jsonb_agg(case when shelf->>'label'='Project records and memory' and not shelf->'tools'?(policy->>'name') then jsonb_set(shelf,'{tools}',shelf->'tools'||jsonb_build_array(policy->>'name')) else shelf end) from jsonb_array_elements(definition->'shelves') shelf));
 end loop;
 select coalesce(max(version),0)+1 into next_version from shared.ai_prompt_versions where prompt_id=prior.prompt_id;
 insert into shared.ai_prompt_versions(prompt_id,version,definition_kind,definition_format_version,metadata,content,definition,flow,available_variables)
  values(prior.prompt_id,next_version,prior.definition_kind,prior.definition_format_version,(prior.metadata-'seed_version'-'source_revision')||jsonb_build_object('publication','server-bound-work-records'),prior.content,definition,prior.flow,prior.available_variables) returning id into version_uuid;
 activation:=activation||jsonb_build_object('bob.tools',version_uuid);
 perform shared.activate_ai_catalog('bob',activation);
end $server_bound_edits_catalog$;
commit;
`
const path = process.argv[2]
if (!path) throw new Error('Pass the migration created by Supabase CLI')
if (process.argv.includes('--check')) {
  if (readFileSync(path,'utf8') !== sql) throw new Error('Work record publication differs from executable contracts')
  console.log('Verified work record contracts and toolbox publication.')
} else writeFileSync(path,sql)
