/** Publish the room_dimensions dataset of search_project_data without replacing live catalog customizations. */
import { readFileSync, writeFileSync } from 'node:fs'
import { DATASETS } from '../supabase/functions/_shared/project-lookup.ts'
const spec = {
  key: 'tools.search_project_data',
  dataset: 'room_dimensions',
  // The executable enum: the published one plus room_dimensions, in this order.
  datasets: [...DATASETS],
  note: ' room_dimensions gives each room in this project with its building and typed dimensions from accepted room measurements: known, conflict (all values) or unknown; nothing is derived.',
}
if (spec.datasets.at(-1) !== spec.dataset) throw new Error('room_dimensions must be the last executable dataset')
const sql = `-- Generated by scripts/build-ai-room-dimensions-catalog.ts.
-- Apply 20261026093000_room_dimensions.sql, deploy ask-bob AND bob-worker from
-- the same source, then apply this publication (room-dimensions-v1). Earlier
-- manifests keep their dataset list. Re-running is a no-op.
begin;
set local lock_timeout='5s';
set local statement_timeout='60s';
do $room_dimensions_publication$
declare spec jsonb:=$room_dimensions_spec$${JSON.stringify(spec)}$room_dimensions_spec$::jsonb;
 prior shared.ai_prompt_versions; next_version integer; version_uuid uuid; definition jsonb; datasets jsonb;
begin
 perform pg_advisory_xact_lock(hashtextextended('ai_catalog:bob',0));
 select v.* into prior from shared.ai_prompts p join shared.ai_prompt_versions v on v.id=p.active_version_id
  where p.app='bob' and p.prompt_key=spec->>'key' and p.retired_at is null for update of p;
 if not found then raise exception 'room_dimensions_contract_missing'; end if;
 datasets:=prior.definition#>'{parameters,properties,dataset,enum}';
 if datasets ? (spec->>'dataset') then return; end if;
 if datasets||jsonb_build_array(spec->>'dataset')<>spec->'datasets' then raise exception 'room_dimensions_datasets_changed'; end if;
 definition:=jsonb_set(prior.definition,'{parameters,properties,dataset,enum}',spec->'datasets');
 definition:=jsonb_set(definition,'{parameters,properties,dataset,description}',
  to_jsonb((definition#>>'{parameters,properties,dataset,description}')||(spec->>'note')));
 select coalesce(max(version),0)+1 into next_version from shared.ai_prompt_versions where prompt_id=prior.prompt_id;
 insert into shared.ai_prompt_versions(prompt_id,version,definition_kind,definition_format_version,metadata,content,definition,flow,available_variables)
  values(prior.prompt_id,next_version,prior.definition_kind,prior.definition_format_version,
   (prior.metadata-'seed_version'-'source_revision')||jsonb_build_object('publication','room-dimensions-v1'),
   prior.content,definition,prior.flow,prior.available_variables) returning id into version_uuid;
 perform shared.activate_ai_catalog('bob',jsonb_build_object(spec->>'key',version_uuid));
end $room_dimensions_publication$;
commit;
`
const target = process.argv.find(arg => arg.endsWith('_ai_room_dimensions_catalog.sql'))
if (!target) throw new Error('Pass the *_ai_room_dimensions_catalog.sql migration path')
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== sql) throw new Error('Room dimensions publication differs from executable tools')
  console.log('Room dimensions catalog matches executable tools')
} else writeFileSync(target, sql)
