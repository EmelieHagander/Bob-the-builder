/** Publish joint fasteners (owner decisions 2026-10-26) without replacing live
 * catalog customizations: the exact old joint item schema becomes the current
 * one in the save, legacy-transition and edit tools, and the lists tool says
 * that it returns the server fastener schedule. Earlier manifests keep theirs. */
import { readFileSync, writeFileSync } from 'node:fs'
import { CONSTRUCTION_SAVE_TOOL } from '../supabase/functions/_shared/construction-draft.ts'
import { CONSTRUCTION_EDIT_TOOL } from '../supabase/functions/_shared/construction-edits.ts'
import { withoutJointFasteners } from '../supabase/functions/_shared/construction-fasteners.ts'

const after = (CONSTRUCTION_SAVE_TOOL.function.parameters.properties.joints as { items: unknown }).items
const editItem = ((CONSTRUCTION_EDIT_TOOL.function.parameters.properties.changes as any).properties.joints.properties.upsert).items
if (JSON.stringify(editItem) !== JSON.stringify(after)) throw new Error('save and edit joint schemas differ')
const before = withoutJointFasteners(after)
const writes = ' Joint fastener: null applies the fixed rule (a screw sized from the board thickness; glue for glued joints). Set a fastener only for an owner choice such as nails, with kind, diameter_mm and length_mm; leave count and spacing_mm null to spread them by rule. Sending null removes an earlier choice.'
const lists = ' The result also gives the server fastener schedule: each joint\'s fastener (rule or owner choice), totals by kind and size, and glue packages. These are rule-of-thumb proposals, not a strength calculation.'
const needs = ' Construction fasteners and glue: quantity_mode=fasteners with fastener_kind (screw, nail or bolt), diameter_mm and length_mm exactly as one totals row of derive_construction_lists gives one need for that size, counted by the server schedule; quantity_mode=glue gives one glue package for a construction with glued joints. Omit definition_id for these modes. These needs may go to Shopping and pack purchases; construction blank needs keep their cut-plan guard.'
const spec = {
  before, after,
  patches: [
    { key: 'tools.save_construction_draft', note: writes, joints: 1 },
    { key: 'tools.transition_legacy_drawing', note: writes, joints: 1 },
    { key: 'tools.edit_construction_parts', note: writes, joints: 1 },
    { key: 'tools.derive_construction_lists', note: lists, joints: 0 },
    { key: 'tools.derive_cad_material_requirement', note: needs, joints: 0 },
  ],
}
const sql = `-- Generated by scripts/build-ai-joint-fasteners-catalog.ts.
-- Apply 20261026170000_construction_fasteners.sql, deploy ask-bob AND
-- bob-worker from the same source, then apply this publication
-- (joint-fasteners-v1). Earlier manifests keep their joint schema. Re-running
-- is a no-op.
begin;
set local lock_timeout='5s';
set local statement_timeout='60s';
create or replace function pg_temp.joint_fastener_walk(node jsonb,old_item jsonb,new_item jsonb) returns jsonb language plpgsql immutable as $walk$
declare result jsonb; k text; v jsonb;
begin
 if node=old_item then return new_item; end if;
 if jsonb_typeof(node)='object' then
  result:='{}';
  for k,v in select * from jsonb_each(node) loop result:=result||jsonb_build_object(k,pg_temp.joint_fastener_walk(v,old_item,new_item)); end loop;
  return result;
 elsif jsonb_typeof(node)='array' then
  return coalesce((select jsonb_agg(pg_temp.joint_fastener_walk(x,old_item,new_item) order by n) from jsonb_array_elements(node) with ordinality y(x,n)),'[]');
 end if;
 return node;
end $walk$;
do $joint_fasteners_publication$
declare spec jsonb:=$joint_fasteners_spec$${JSON.stringify(spec)}$joint_fasteners_spec$::jsonb;
 patch jsonb; prior shared.ai_prompt_versions; next_version integer; version_uuid uuid; definition jsonb; activation jsonb:='{}'; found_items integer;
begin
 perform pg_advisory_xact_lock(hashtextextended('ai_catalog:bob',0));
 for patch in select value from jsonb_array_elements(spec->'patches') loop
  select v.* into prior from shared.ai_prompts p join shared.ai_prompt_versions v on v.id=p.active_version_id
   where p.app='bob' and p.prompt_key=patch->>'key' and p.retired_at is null for update of p;
  if not found then raise exception 'joint_fasteners_contract_missing: %',patch->>'key'; end if;
  if prior.metadata->>'joint_fastener_version'='1' then continue; end if;
  definition:=pg_temp.joint_fastener_walk(prior.definition,spec->'before',spec->'after');
  select count(*) into found_items from jsonb_path_query(definition,'strict $.**') x where x=spec->'after';
  if found_items<>(patch->>'joints')::integer then raise exception 'joint_fasteners_schema_changed: % (% joint schemas)',patch->>'key',found_items; end if;
  definition:=jsonb_set(definition,'{additional_description}',to_jsonb(coalesce(definition->>'additional_description','')||(patch->>'note')));
  select coalesce(max(version),0)+1 into next_version from shared.ai_prompt_versions where prompt_id=prior.prompt_id;
  insert into shared.ai_prompt_versions(prompt_id,version,definition_kind,definition_format_version,metadata,content,definition,flow,available_variables)
   values(prior.prompt_id,next_version,prior.definition_kind,prior.definition_format_version,
    (prior.metadata-'seed_version'-'source_revision')||jsonb_build_object('publication','joint-fasteners-v1','joint_fastener_version',1),
    prior.content,definition,prior.flow,prior.available_variables) returning id into version_uuid;
  activation:=activation||jsonb_build_object(patch->>'key',version_uuid);
 end loop;
 if activation<>'{}'::jsonb then perform shared.activate_ai_catalog('bob',activation); end if;
end $joint_fasteners_publication$;
commit;
`
const target = process.argv.find(arg => arg.endsWith('_ai_joint_fasteners_catalog.sql'))
if (!target) throw new Error('Pass the *_ai_joint_fasteners_catalog.sql migration path')
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== sql) throw new Error('Joint fasteners publication differs from executable tools')
  console.log('Joint fasteners catalog matches executable tools')
} else writeFileSync(target, sql)
