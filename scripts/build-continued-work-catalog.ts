import {readFileSync,writeFileSync} from 'node:fs'
import {CONSTRUCTION_NOTES_SCHEMA,CONSTRUCTION_NOTES_NOTE} from '../supabase/functions/_shared/construction-text.ts'
const specs=[{key:'bob.tools',patch:{continued_work_version:1}},...['tools.edit_construction_parts','tools.change_construction_parameters'].map(key=>({key,text_schema:CONSTRUCTION_NOTES_SCHEMA,note:CONSTRUCTION_NOTES_NOTE}))]
const sql=`-- Generated by scripts/build-continued-work-catalog.ts. Activate after both Bob bundles.
begin;
set local lock_timeout='5s';
do $continued_work_catalog$
declare specs jsonb:=$continued_work_spec$${JSON.stringify(specs)}$continued_work_spec$;
 item jsonb; prior shared.ai_prompt_versions; def jsonb; version_id uuid; next_version integer; activation jsonb:='{}';
begin
 perform pg_advisory_xact_lock(hashtext('ai_catalog:bob'));
 for item in select value from jsonb_array_elements(specs) loop
  select v.* into prior from shared.ai_prompts p join shared.ai_prompt_versions v on v.id=p.active_version_id where p.app='bob' and p.prompt_key=item->>'key' and p.retired_at is null for update of p;
  if not found then raise exception 'continued_work_catalog_missing';end if;
  def:=prior.definition||coalesce(item->'patch','{}');
  if item?'text_schema' then def:=jsonb_set(def,'{parameters,properties,text}',item->'text_schema');def:=jsonb_set(def,'{description}',to_jsonb((def->>'description')||(item->>'note')));end if;
  select coalesce(max(version),0)+1 into next_version from shared.ai_prompt_versions where prompt_id=prior.prompt_id;
  insert into shared.ai_prompt_versions(prompt_id,version,definition_kind,definition_format_version,metadata,content,definition,flow,available_variables)
   values(prior.prompt_id,next_version,prior.definition_kind,prior.definition_format_version,(prior.metadata-'seed_version'-'source_revision')||jsonb_build_object('publication','continued-work-v1'),prior.content,def,prior.flow,prior.available_variables) returning id into version_id;
  activation:=activation||jsonb_build_object(item->>'key',version_id);
 end loop;
 perform shared.activate_ai_catalog('bob',activation);
end $continued_work_catalog$;
commit;
`
const path=process.argv.find(p=>p.endsWith('_continued_work_catalog.sql'));if(!path)throw Error('Pass the catalog migration path')
if(process.argv.includes('--check')){if(readFileSync(path,'utf8')!==sql)throw Error('Continued work catalog differs')}else writeFileSync(path,sql)
