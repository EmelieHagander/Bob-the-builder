/** Publish the exact fastener and glue need rule (owner decision 2026-10-26)
 * without replacing live catalog customizations: one note on the derive tool,
 * so Bob omits a waste allowance before calling. The server refuses one with
 * fastener_quantity_exact (20261026190000_exact_fastener_needs.sql). Earlier
 * manifests keep their notes. */
import { readFileSync, writeFileSync } from 'node:fs'

const needs = ' Fastener and glue needs are exact counts from the schedule, so omit waste_percent (or send 0); purchase_increment stays the pack size. If a spare is sensible, recommend it in the reply as a suggestion, separate from the need.'
const spec = { patches: [{ key: 'tools.derive_cad_material_requirement', note: needs }] }
const sql = `-- Generated by scripts/build-ai-exact-fasteners-catalog.ts.
-- Apply 20261026190000_exact_fastener_needs.sql, deploy ask-bob AND
-- bob-worker from the same source, then apply this publication
-- (exact-fasteners-v1). It requires joint-fasteners-v1 on the same tool.
-- Earlier manifests keep their notes. Re-running is a no-op.
begin;
set local lock_timeout='5s';
set local statement_timeout='60s';
do $exact_fasteners_publication$
declare spec jsonb:=$exact_fasteners_spec$${JSON.stringify(spec)}$exact_fasteners_spec$::jsonb;
 patch jsonb; prior shared.ai_prompt_versions; next_version integer; version_uuid uuid; definition jsonb; activation jsonb:='{}';
begin
 perform pg_advisory_xact_lock(hashtextextended('ai_catalog:bob',0));
 for patch in select value from jsonb_array_elements(spec->'patches') loop
  select v.* into prior from shared.ai_prompts p join shared.ai_prompt_versions v on v.id=p.active_version_id
   where p.app='bob' and p.prompt_key=patch->>'key' and p.retired_at is null for update of p;
  if not found then raise exception 'exact_fasteners_contract_missing: %',patch->>'key'; end if;
  if prior.metadata->>'exact_fastener_version'='1' then continue; end if;
  if prior.metadata->>'joint_fastener_version' is distinct from '1' then raise exception 'exact_fasteners_requires_joint_fasteners: %',patch->>'key'; end if;
  definition:=jsonb_set(prior.definition,'{additional_description}',to_jsonb(coalesce(prior.definition->>'additional_description','')||(patch->>'note')));
  select coalesce(max(version),0)+1 into next_version from shared.ai_prompt_versions where prompt_id=prior.prompt_id;
  insert into shared.ai_prompt_versions(prompt_id,version,definition_kind,definition_format_version,metadata,content,definition,flow,available_variables)
   values(prior.prompt_id,next_version,prior.definition_kind,prior.definition_format_version,
    (prior.metadata-'seed_version'-'source_revision')||jsonb_build_object('publication','exact-fasteners-v1','exact_fastener_version',1),
    prior.content,definition,prior.flow,prior.available_variables) returning id into version_uuid;
  activation:=activation||jsonb_build_object(patch->>'key',version_uuid);
 end loop;
 if activation<>'{}'::jsonb then perform shared.activate_ai_catalog('bob',activation); end if;
end $exact_fasteners_publication$;
commit;
`
const target = process.argv.find(arg => arg.endsWith('_ai_exact_fasteners_catalog.sql'))
if (!target) throw new Error('Pass the *_ai_exact_fasteners_catalog.sql migration path')
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== sql) throw new Error('Exact fasteners publication differs from its builder')
  console.log('Exact fasteners catalog matches its builder')
} else writeFileSync(target, sql)
