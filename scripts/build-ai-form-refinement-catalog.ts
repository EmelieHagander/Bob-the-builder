import { readFileSync, writeFileSync } from 'node:fs'
import { FORM_REFINEMENT_SCHEMA } from '../supabase/functions/_shared/construction-form.ts'
import { FORM_REFINEMENT_NOTE } from '../supabase/functions/_shared/construction-draft.ts'

const spec = { schema: FORM_REFINEMENT_SCHEMA, note: FORM_REFINEMENT_NOTE }
const sql = `-- Generated by scripts/build-ai-form-refinement-catalog.ts.
-- Apply core 20261027090942_construction_form_refinement.sql, deploy compatible
-- ask-bob AND bob-worker, then activate this publication. Old manifests retain
-- their schema and tool path. No workflow or deployment starts automatically.
begin;
set local lock_timeout='5s';
set local statement_timeout='60s';
do $form_refinement_publication$
declare spec jsonb:=$form_refinement_spec$${JSON.stringify(spec)}$form_refinement_spec$::jsonb;
 prior shared.ai_prompt_versions; definition jsonb; next_version integer; version_uuid uuid;
begin
 perform pg_advisory_xact_lock(hashtextextended('ai_catalog:bob',0));
 select v.* into prior from shared.ai_prompts p join shared.ai_prompt_versions v on v.id=p.active_version_id
  where p.app='bob' and p.prompt_key='tools.save_construction_draft' and p.retired_at is null for update of p;
 if not found then raise exception 'form_refinement_contract_missing'; end if;
 if prior.metadata->>'form_refinement_version'='1' then return; end if;
 definition:=jsonb_set(prior.definition,'{parameters,properties,form_refinement}',spec->'schema');
 definition:=jsonb_set(definition,'{parameters,required}',(definition#>'{parameters,required}')||jsonb_build_array('form_refinement'));
 definition:=jsonb_set(definition,'{required_parameters}',definition#>'{parameters,required}');
 definition:=jsonb_set(definition,'{description}',to_jsonb((definition->>'description')||(spec->>'note')));
 select coalesce(max(version),0)+1 into next_version from shared.ai_prompt_versions where prompt_id=prior.prompt_id;
 insert into shared.ai_prompt_versions(prompt_id,version,definition_kind,definition_format_version,metadata,content,definition,flow,available_variables)
  values(prior.prompt_id,next_version,prior.definition_kind,prior.definition_format_version,
   (prior.metadata-'seed_version'-'source_revision')||jsonb_build_object('publication','form-refinement-v1','form_refinement_version',1),
   prior.content,definition,prior.flow,prior.available_variables) returning id into version_uuid;
 perform shared.activate_ai_catalog('bob',jsonb_build_object('tools.save_construction_draft',version_uuid));
end $form_refinement_publication$;
commit;
`
const target=process.argv.find(arg=>arg.endsWith('_ai_form_refinement_catalog.sql'))
if(!target)throw Error('Pass the *_ai_form_refinement_catalog.sql migration path')
if(process.argv.includes('--check')){
 if(readFileSync(target,'utf8')!==sql)throw Error('FORM refinement catalog is stale')
}else writeFileSync(target,sql)
