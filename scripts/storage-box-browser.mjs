import assert from 'node:assert/strict'
import { readFile } from 'node:fs/promises'

/** Production UI/data adapter; shared fixture services only. SQL/RLS have their own tests. */
export async function verifyStorageBoxBrowser(page, base, fixture, width) {
  await page.goto(base + '#/artifacts?area=areaA')
  await page.getByRole('button', { name: 'Draw storage box', exact: true }).click()
  let editor = page.getByRole('dialog', { name: 'Draw a storage box', exact: true })
  await editor.getByLabel('Drawing title', { exact: true }).fill('Test storage box')
  await editor.getByLabel('Outside height (mm)', { exact: true }).fill('18')
  await editor.getByRole('alert').getByText(/no usable interior/).waitFor()
  assert(await editor.getByRole('button', { name: 'Save drawing', exact: true }).isDisabled())
  await editor.getByLabel('Outside height (mm)', { exact: true }).fill('350')
  await editor.locator('.box-dimensions').getByText('764 × 332 × 564 mm', { exact: true }).waitFor()
  assert.equal(await editor.getByRole('button', { name: 'Save SVG', exact: true }).count(), 0, 'Unsaved working previews are not exported as saved drawings')
  await editor.getByRole('button', { name: 'Save drawing', exact: true }).click()
  let detail = page.getByRole('dialog', { name: 'Test storage box · Version 1', exact: true })
  await detail.waitFor()
  await detail.locator('.box-parts').getByRole('rowheader', { name: 'F1 · Front / back', exact: true }).waitFor()
  const current = [...fixture.records.values()].find(row => row.title === 'Test storage box')
  assert(current)
  const original = structuredClone(fixture.parametric.get(`${current.id}:1`))
  for (const [name, text] of [['Front elevation', 'F1 width 764'], ['Plan · open top', 'Inside 564'], ['Section A–A · through centre', 'Inside height 332']]) {
    await detail.getByRole('button', { name, exact: true }).click()
    await detail.locator('svg').getByText(text, { exact: true }).waitFor()
  }
  assert(await detail.locator('.box-drawing-viewport').evaluate(el => el.scrollWidth <= el.clientWidth + 1), 'Default view must show the whole drawing, not crop it on phones')
  await detail.getByRole('button', { name: 'Zoom drawing in', exact: true }).click()
  await detail.getByText('150%', { exact: true }).waitFor()
  assert(await detail.locator('.box-drawing-viewport').evaluate(el => el.scrollWidth > el.clientWidth), 'Zoomed details remain scrollable inside the drawing')
  await detail.getByRole('button', { name: 'Reset zoom', exact: true }).click()
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), 'Drawing preview must not overflow the page')
  for (const button of await detail.locator('.box-drawing').getByRole('button').all()) {
    const b = await button.boundingBox()
    assert(!b || b.width >= 44 && b.height >= 44, 'Drawing buttons need readable touch targets')
  }
  const download = page.waitForEvent('download')
  await detail.getByRole('button', { name: 'Save SVG', exact: true }).click()
  const file = await download
  assert(file.suggestedFilename().includes('-r1-section.svg'))
  const svg = await readFile(await file.path(), 'utf8')
  assert.match(svg, /Revision 1/); assert.match(svg, /Inside height 332/); assert.match(svg, /NOT TO SCALE/)
  const csvDownload = page.waitForEvent('download')
  await detail.getByRole('button', { name: 'Save parts CSV', exact: true }).click()
  const csv = await readFile(await (await csvDownload).path(), 'utf8')
  assert.match(csv, /F1,Front \/ back,2,764,332,18/)
  // Suppress the native print dialog, not the actual print rendering path.
  await page.evaluate(() => { window.print = () => { window.__boxPrintCalled = true } })
  await detail.getByRole('button', { name: 'Print / PDF', exact: true }).click()
  await page.waitForFunction(() => window.__boxPrintCalled && document.body.classList.contains('printing-box-drawing'))
  await page.emulateMedia({ media: 'print' })
  assert.equal(await page.locator('.box-print-page').count(), 4)
  assert.equal(await page.locator('.box-print-pack svg').count(), 3)
  assert.equal(await page.locator('.box-print-pack').isVisible(), true)
  assert.equal(await page.locator('#root').isVisible(), false)
  await page.emulateMedia({ media: 'screen' })
  await page.evaluate(() => window.dispatchEvent(new Event('afterprint')))
  await page.locator('.box-print-pack').waitFor({ state: 'detached' })
  await detail.getByRole('button', { name: 'Close', exact: true }).click()
  const card = page.getByRole('article', { name: 'Test storage box', exact: true })
  await card.getByRole('button', { name: 'Revise', exact: true }).click()
  editor = page.getByRole('dialog', { name: 'Edit storage box dimensions', exact: true })
  await editor.getByLabel('Outside height (mm)', { exact: true }).fill('300')
  await editor.getByLabel('Reason for change', { exact: true }).fill('Lower box, same footprint')
  fixture.rejectNext = true
  await editor.getByRole('button', { name: 'Save new drawing version', exact: true }).click()
  await editor.getByText('Project target changed. Reload before saving the drawing.', { exact: true }).waitFor()
  assert.equal(await editor.getByLabel('Outside height (mm)', { exact: true }).inputValue(), '300')
  assert.deepEqual(fixture.parametric.get(`${current.id}:1`), original)
  await editor.getByRole('button', { name: 'Cancel', exact: true }).click()
  await card.getByRole('button', { name: 'Revise', exact: true }).click()
  editor = page.getByRole('dialog', { name: 'Edit storage box dimensions', exact: true })
  await editor.getByLabel('Outside height (mm)', { exact: true }).fill('300')
  await editor.getByLabel('Reason for change', { exact: true }).fill('Lower box, same footprint')
  await editor.getByRole('button', { name: 'Save new drawing version', exact: true }).click()
  await editor.waitFor({ state: 'hidden' })
  await page.reload(); await card.getByRole('button', { name: 'Open drawing', exact: true }).click()
  detail = page.getByRole('dialog', { name: 'Test storage box · Version 2', exact: true })
  await detail.locator('.box-dimensions').getByText('764 × 282 × 564 mm', { exact: true }).waitFor()
  assert.deepEqual(fixture.parametric.get(`${current.id}:1`), original)
  await detail.getByRole('button', { name: 'Close', exact: true }).click()
  // The same exact-revision link used in Bob's receipt must survive reload.
  await page.goto(base + `#/artifacts?area=areaA&drawing=${current.id}&revision=1`)
  detail = page.getByRole('dialog', { name: 'Test storage box · Version 1', exact: true })
  await detail.locator('.box-dimensions').getByText('764 × 332 × 564 mm', { exact: true }).waitFor()
  await detail.getByRole('button', { name: 'Plan · open top', exact: true }).click()
  await detail.getByRole('button', { name: 'Plan · open top', exact: true }).evaluate(async el => {
    await Promise.all(el.getAnimations({ subtree: true }).map(animation => animation.finished))
  })
  await page.screenshot({ path: `test-results/storage-box-${width}.png` })
  await page.reload()
  await detail.locator('.box-dimensions').getByText('764 × 332 × 564 mm', { exact: true }).waitFor()
  await detail.getByRole('button', { name: 'Close', exact: true }).click()
  assert(!page.url().includes('drawing='))
  console.log(`Parametric storage box create/edit/conflict/reload/history/SVG/CSV/print passed at ${width}px; HTTP fixtures, no AI.`)
}
