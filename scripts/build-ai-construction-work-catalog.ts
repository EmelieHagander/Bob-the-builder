/** Only tool interfaces and deterministic availability change. Agent prompts,
 * model profiles, six core names and inactive reader/reviewer roles stay pinned. */
import { readFileSync, writeFileSync } from 'node:fs'
import { CONSTRUCTION_EVIDENCE_CHECK_TOOL, CONSTRUCTION_PARAMETER_REFRESH_TOOL } from '../supabase/functions/_shared/construction-draft.ts'
import { CONSTRUCTION_EVIDENCE_VIEW_TOOL } from '../supabase/functions/_shared/construction-views.ts'
import { CONSTRUCTION_EDIT_TOOL } from '../supabase/functions/_shared/construction-edits.ts'
import { withConstructionWorkRead, withConstructionWorkWrite, withConstructionWorkCheck } from '../supabase/functions/_shared/construction-work.ts'

const specs=[
 [CONSTRUCTION_EVIDENCE_VIEW_TOOL,withConstructionWorkRead(CONSTRUCTION_EVIDENCE_VIEW_TOOL)],
 [CONSTRUCTION_PARAMETER_REFRESH_TOOL,withConstructionWorkWrite(CONSTRUCTION_PARAMETER_REFRESH_TOOL)],
 [CONSTRUCTION_EDIT_TOOL,withConstructionWorkWrite(CONSTRUCTION_EDIT_TOOL)],
 [CONSTRUCTION_EVIDENCE_CHECK_TOOL,withConstructionWorkCheck(CONSTRUCTION_EVIDENCE_CHECK_TOOL)],
].map(([old,tool])=>({key:'tools.'+tool.function.name,note:tool.function.description.slice(old.function.description.length),
 patch:{parameters:tool.function.parameters,required_parameters:tool.function.parameters.required}}))
specs.push({key:'bob.tools',note:'',patch:{operation_followups:[
 {after_tool:'read_construction_draft',statuses:['ok'],when:{field:'work_operation',equals:'parts'},tools:['edit_construction_parts']},
 {after_tool:'change_construction_parameters',statuses:['saved'],tools:['check_construction_draft']},
 {after_tool:'edit_construction_parts',statuses:['saved'],tools:['check_construction_draft']},
 {after_tool:'save_construction_draft',statuses:['saved'],tools:['check_construction_draft']},
 {after_tool:'check_construction_draft',statuses:['checked'],when:{field:'concept_ready',equals:true},tools:['design_project_cad']},
]} as any})
const sql=`-- Generated by scripts/build-ai-construction-work-catalog.ts.
-- Install construction_work_operations and both Edge runtimes first.
-- No model-role prompts, profiles or dormant tool policies are changed.
begin;
set local lock_timeout='5s';
set local statement_timeout='60s';
do $construction_work_publication$
declare specs jsonb:=$construction_work_spec$${JSON.stringify(specs)}$construction_work_spec$::jsonb;
 item jsonb; prior shared.ai_prompt_versions; definition jsonb; next_version integer; version_uuid uuid; activation jsonb:='{}';
begin
 perform pg_advisory_xact_lock(hashtextextended('ai_catalog:bob',0));
 for item in select value from jsonb_array_elements(specs) loop
  select v.* into prior from shared.ai_prompts p join shared.ai_prompt_versions v on v.id=p.active_version_id
   where p.app='bob' and p.prompt_key=item->>'key' and p.retired_at is null for update of p;
  if not found then raise exception 'construction_work_contract_missing'; end if;
  if prior.metadata->>'construction_work_version'='1' then continue; end if;
  definition:=prior.definition||(item->'patch');
  if item->>'note'<>'' then definition:=jsonb_set(definition,'{description}',to_jsonb((prior.definition->>'description')||(item->>'note'))); end if;
  select coalesce(max(version),0)+1 into next_version from shared.ai_prompt_versions where prompt_id=prior.prompt_id;
  insert into shared.ai_prompt_versions(prompt_id,version,definition_kind,definition_format_version,metadata,content,definition,flow,available_variables)
   values(prior.prompt_id,next_version,prior.definition_kind,prior.definition_format_version,
    (prior.metadata-'seed_version'-'source_revision')||jsonb_build_object('publication','construction-work-v1','construction_work_version',1),
    prior.content,definition,prior.flow,prior.available_variables) returning id into version_uuid;
  activation:=activation||jsonb_build_object(item->>'key',version_uuid);
 end loop;
 if activation<>'{}'::jsonb then perform shared.activate_ai_catalog('bob',activation); end if;
end $construction_work_publication$;
commit;
`
const target=process.argv.find(arg=>arg.endsWith('_ai_construction_work_catalog.sql'))
if(!target)throw Error('Pass the *_ai_construction_work_catalog.sql migration path')
if(process.argv.includes('--check')){
 if(readFileSync(target,'utf8')!==sql)throw Error('Construction work publication is stale')
}else writeFileSync(target,sql)
