/** Publish the integrated task-resume guidance without exposing the ledger. */
import {readFileSync,writeFileSync} from 'node:fs'
const priorSql=readFileSync('supabase/migrations/20261012090928_ai_task_budget_catalog.sql','utf8')
const oldGuard=JSON.parse(priorSql.match(/\$task_budget_tool\$([\s\S]+?)\$task_budget_tool\$/)![1]).additional_description
const guidance='A previous attempt ended without a usable result. Stop this attempt and tell the owner plainly. On a new owner message about this same drawing, call design_project_cad with its existing request_id and saved handoff. Reuse a source-current draft; do not restart research or design just to retry review. Automatic continuations of this attempt cannot restart the same unacknowledged operation. If prior work is still active, report the wait and finish this reply.'
if(/budget|money|allocation|\$|usd_limit|spent_usd/i.test(guidance))throw new Error('Resume guidance exposes the ledger')
const sql=`-- Generated by scripts/build-ai-task-resume-catalog.ts.
-- Install guarded submission/task-attempt SQL and matching runtimes first.
begin;
do $task_resume_catalog$
declare prior shared.ai_prompt_versions; next_version integer; version_uuid uuid; activation jsonb:='{}'; definition jsonb;
begin
 perform pg_advisory_xact_lock(hashtextextended('ai_catalog:bob',0));
 select v.* into prior from shared.ai_prompts p join shared.ai_prompt_versions v on v.id=p.active_version_id
  where p.app='bob' and p.prompt_key='tools.design_project_cad' for update of p;
 if not found then raise exception 'task_resume_tool_missing'; end if;
 -- Remove only the exact server-budget paragraph added by the older publication.
 definition:=jsonb_set(prior.definition,'{additional_description}',to_jsonb(btrim(replace(coalesce(prior.definition->>'additional_description',''),$old_guard$${oldGuard}$old_guard$,''))));
 select coalesce(max(version),0)+1 into next_version from shared.ai_prompt_versions where prompt_id=prior.prompt_id;
 insert into shared.ai_prompt_versions(prompt_id,version,definition_kind,definition_format_version,metadata,content,definition,flow,available_variables)
  values(prior.prompt_id,next_version,prior.definition_kind,prior.definition_format_version,
   (prior.metadata-'seed_version'-'source_revision')||jsonb_build_object('publication','guarded-task-resume'),prior.content,definition,prior.flow,prior.available_variables) returning id into version_uuid;
 activation:=activation||jsonb_build_object('tools.design_project_cad',version_uuid);
 select v.* into prior from shared.ai_prompts p join shared.ai_prompt_versions v on v.id=p.active_version_id
  where p.app='bob' and p.prompt_key='feedback.bob-budget-stop.resume.9c3a74e182d5' for update of p;
 if not found then raise exception 'task_resume_guidance_missing'; end if;
 select coalesce(max(version),0)+1 into next_version from shared.ai_prompt_versions where prompt_id=prior.prompt_id;
 insert into shared.ai_prompt_versions(prompt_id,version,definition_kind,definition_format_version,metadata,content,definition,flow,available_variables)
  values(prior.prompt_id,next_version,prior.definition_kind,prior.definition_format_version,
   (prior.metadata-'seed_version'-'source_revision')||jsonb_build_object('publication','guarded-task-resume'),$resume_guidance$${guidance}$resume_guidance$,prior.definition,prior.flow,prior.available_variables) returning id into version_uuid;
 activation:=activation||jsonb_build_object('feedback.bob-budget-stop.resume.9c3a74e182d5',version_uuid);
 perform shared.activate_ai_catalog('bob',activation);
end $task_resume_catalog$;
commit;
`
const path=process.argv[2]
if(!path)throw new Error('Pass the migration created by Supabase CLI')
if(process.argv.includes('--check')){
 if(readFileSync(path,'utf8')!==sql)throw new Error('Task resume publication differs from its preserved source')
 console.log('Verified integrated task-resume publication')
}else writeFileSync(path,sql)
