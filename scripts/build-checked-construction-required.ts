/** Preserve the complete current K3/role guard; require its source for new CAD. */
import {readFileSync,writeFileSync} from 'node:fs'
const prior=readFileSync('supabase/migrations/20261011090115_construction_instance_roles.sql','utf8')
const current=prior.match(/create or replace function bob_private\.validate_cad_construction_source\(\) returns trigger[\s\S]+?end \$\$;/)?.[0]
if(!current)throw new Error('Current construction publication guard is missing')
const old=" if pin is null then\n  if prior.manifest?'bob_construction' then raise exception 'construction_pin_required' using errcode='22023'; end if;\n  return new;\n end if;"
if(!current.includes(old))throw new Error('The reviewed optional-source boundary changed')
const body=current.replace(old," if pin is null then raise exception 'construction_pin_required' using errcode='22023'; end if;")
// Change the existing atomic packet/scope boundary, retaining its owner, claim,
// CAS, replay, cancellation and restoration wrappers. No new public RPC.
const lifecycle=readFileSync('supabase/migrations/20260930040222_project_drawing_request_lifecycle.sql','utf8')
const packet=lifecycle.match(/create function bob\.bob_drawing_request\(p_project[\s\S]+?end \$\$;/)?.[0]
if(!packet)throw new Error('Existing atomic request boundary is missing')
const scopeCheck=" if jsonb_build_object('area_id',p_payload->'brief'->'area_id','component_id',p_payload->'brief'->'component_id','step_id',p_payload->'brief'->'step_id','artifact_id',p_payload->'brief'->'artifact_id') is distinct from r.scope then raise exception 'drawing_scope_changed' using errcode='40001'; end if;"
if(!packet.includes(scopeCheck))throw new Error('Request scope boundary changed')
const adoption=` if jsonb_build_object('area_id',p_payload->'brief'->'area_id','component_id',p_payload->'brief'->'component_id','step_id',p_payload->'brief'->'step_id','artifact_id',p_payload->'brief'->'artifact_id') is distinct from r.scope then
  -- A saved pre-gate request may establish its first construction source only.
  -- Scope and packet advance in this same transaction and existing CAS/replay.
  if r.scope->>'artifact_id' is not null or r.revision=0
   or r.scope-'artifact_id' is distinct from jsonb_build_object('area_id',p_payload->'brief'->'area_id','component_id',p_payload->'brief'->'component_id','step_id',p_payload->'brief'->'step_id')
   or coalesce(p_payload#>>'{brief,artifact_id}','')!~*'^[0-9a-f]{8}-[0-9a-f]{4}-[1-5][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$'
   or coalesce(p_payload#>>'{brief,construction_revision}','')!~'^[1-9][0-9]{0,8}$'
   then raise exception 'drawing_scope_changed' using errcode='40001'; end if;
  select * into packet from bob_private.drawing_requests where id=p_id and thread_id=p_thread;
  if not found or packet.revision<>r.revision or packet.payload#>>'{brief,construction_revision}' is not null
   or coalesce(packet.payload#>'{draft,construction}','null'::jsonb)<>'null'::jsonb then raise exception 'drawing_scope_changed' using errcode='40001'; end if;
  perform 1 from bob.artifacts a
   join bob.artifact_revisions v on v.artifact_id=a.id and v.revision=a.current_revision
   join bob.artifact_construction_revisions c on c.artifact_id=a.id and c.artifact_revision=a.current_revision
   where a.project_id=p_project and a.id=(p_payload#>>'{brief,artifact_id}')::uuid
    and a.current_revision=(p_payload#>>'{brief,construction_revision}')::integer and not v.archived
    and a.area_id is not distinct from r.scope->>'area_id' for share of a;
  if not found or (select source_state from bob_private.artifact_source_assessment(p_project,(p_payload#>>'{brief,artifact_id}')::uuid,(p_payload#>>'{brief,construction_revision}')::integer)) is distinct from 'current'
   then raise exception 'drawing_scope_changed' using errcode='40001'; end if;
  r.scope:=jsonb_set(r.scope,'{artifact_id}',p_payload#>'{brief,artifact_id}');
  update bob_private.project_drawing_requests set scope=r.scope where id=p_id;
 end if;`
const requestBody=packet.replace('create function bob.bob_drawing_request(', 'create or replace function bob.bob_drawing_request_before_restoration(').replace(scopeCheck,()=>adoption)
const sql=`-- Generated by scripts/build-checked-construction-required.ts.
-- Require a checked source for every new CAD publication. Historical rows stay
-- unchanged; exact archive/restore copies retain the existing lifecycle guard.
-- An unbound saved request can adopt its first source atomically; pins cannot switch.
begin;
set local lock_timeout='5s';
set local statement_timeout='60s';
${body}
${requestBody}
commit;
`
const path=process.argv[2]
if(!path)throw new Error('Pass the migration created by Supabase CLI')
if(process.argv.includes('--check')){
 if(readFileSync(path,'utf8')!==sql)throw new Error('Mandatory construction guard differs from reviewed source')
 console.log('Verified mandatory construction source; remaining K3/role guards and lifecycle copies unchanged')
}else writeFileSync(path,sql)
