/** Owner decision 2026-10-29: one material search answers what it is, whether
 * the household has it and what it costs. Publishes the search tool text and
 * its pin only; pinned manifests keep the earlier definition-only search. */
import { readFileSync, writeFileSync } from 'node:fs'

export const MATERIAL_LOOKUP_NOTE = ' For entity=materials without property filters each row is the combined material lookup:'
  + ' exact id and revision to pin, material, size in mm (fasteners: width_mm is the shank diameter), unit, weight, aliases,'
  + " the caller's household stock at home and the latest shared store prices, each with when it last changed."
  + ' unreviewed=true marks a shared entry nobody has reviewed. Null means unknown, never zero or absent.'
const specs = [{ key: 'tools.search_material_catalog', append: MATERIAL_LOOKUP_NOTE }]

const sql = `-- Generated by scripts/build-material-lookup-catalog.ts.
-- Owner decision 2026-10-29: material search returns the combined lookup row.
-- Install both matching Edge runtimes and bob.material_lookup before activation.
begin;
set local lock_timeout='5s';
set local statement_timeout='60s';
do $material_lookup_publication$
declare specs jsonb:=$material_lookup_spec$${JSON.stringify(specs)}$material_lookup_spec$::jsonb;
 item jsonb; prior shared.ai_prompt_versions; definition jsonb; next_version integer; version_uuid uuid; activation jsonb:='{}';
begin
 perform pg_advisory_xact_lock(hashtextextended('ai_catalog:bob',0));
 for item in select value from jsonb_array_elements(specs) loop
  select v.* into prior from shared.ai_prompts p join shared.ai_prompt_versions v on v.id=p.active_version_id
   where p.app='bob' and p.prompt_key=item->>'key' and p.retired_at is null for update of p;
  if not found then raise exception 'material_lookup_contract_missing'; end if;
  if prior.metadata->>'material_lookup_version'='1' then continue; end if;
  definition:=jsonb_set(prior.definition,'{description}',to_jsonb((prior.definition->>'description')||(item->>'append')));
  select coalesce(max(version),0)+1 into next_version from shared.ai_prompt_versions where prompt_id=prior.prompt_id;
  insert into shared.ai_prompt_versions(prompt_id,version,definition_kind,definition_format_version,metadata,content,definition,flow,available_variables)
   values(prior.prompt_id,next_version,prior.definition_kind,prior.definition_format_version,
    (prior.metadata-'seed_version'-'source_revision')||jsonb_build_object('publication','material-lookup-v1','material_lookup_version',1),
    prior.content,definition,prior.flow,prior.available_variables) returning id into version_uuid;
  activation:=activation||jsonb_build_object(item->>'key',version_uuid);
 end loop;
 if activation<>'{}'::jsonb then perform shared.activate_ai_catalog('bob',activation); end if;
end $material_lookup_publication$;
commit;
`
const target = process.argv.find(arg => arg.endsWith('_material_lookup_catalog.sql'))
if (target) {
  if (process.argv.includes('--check')) { if (readFileSync(target, 'utf8') !== sql) throw Error('Material lookup publication is stale') }
  else writeFileSync(target, sql)
} else if (process.argv[1]?.endsWith('build-material-lookup-catalog.ts')) throw Error('Pass the *_material_lookup_catalog.sql migration path')
