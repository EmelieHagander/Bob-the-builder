/** Owner decision 2026-10-29: six permanent tools plus four chosen by where the
 * project is, all loaded in full from the first step, and every other tool
 * card says when to use the tool and what it gives. Publishes bob.tools and
 * tool cards only; no agent prompt, model profile or role changes. Pinned
 * manifests keep theirs. Cards live in scripts/data/tool-cards.json. */
import { readFileSync, writeFileSync } from 'node:fs'

type Cards = { core_tools_before: string[]; core_tools: string[]; phase_tools: Record<string, string[]>; cards: Record<string, { before: string; card: string }> }
const data = JSON.parse(readFileSync(new URL('./data/tool-cards.json', import.meta.url), 'utf8')) as Cards
const specs = [
 { key: 'bob.tools', core_tools_before: data.core_tools_before, core_tools: data.core_tools, phase_tools: data.phase_tools },
 ...Object.entries(data.cards).sort(([a], [b]) => a < b ? -1 : 1).map(([name, c]) => ({ key: 'tools.' + name, card_before: c.before, card: c.card })),
]
export const PHASE_TOOLS_SPECS = specs
const sql = `-- Generated by scripts/build-bob-phase-tools-catalog.ts from scripts/data/tool-cards.json.
-- Owner decision 2026-10-29: six permanent tools plus four by project phase
-- (design while drawing work is pending), loaded in full from the first step,
-- and cards that say when to use each other tool and what it gives.
-- Install both matching Edge runtimes before activation. Existing manifests remain pinned.
begin;
set local lock_timeout='5s';
set local statement_timeout='60s';
do $phase_tools_publication$
declare specs jsonb:=$phase_tools_spec$${JSON.stringify(specs)}$phase_tools_spec$::jsonb;
 item jsonb; prior shared.ai_prompt_versions; definition jsonb; next_version integer; version_uuid uuid; activation jsonb:='{}';
begin
 perform pg_advisory_xact_lock(hashtextextended('ai_catalog:bob',0));
 for item in select value from jsonb_array_elements(specs) loop
  select v.* into prior from shared.ai_prompts p join shared.ai_prompt_versions v on v.id=p.active_version_id
   where p.app='bob' and p.prompt_key=item->>'key' and p.retired_at is null for update of p;
  if not found then raise exception 'phase_tools_contract_missing: %',item->>'key'; end if;
  if prior.metadata->>'phase_tools_version'='1' then continue; end if;
  definition:=prior.definition;
  if item ? 'card' then
   -- A drifted card stops the publication instead of overwriting newer text.
   if definition->>'card_description' is distinct from item->>'card_before' then raise exception 'phase_tools_card_changed: %',item->>'key'; end if;
   definition:=jsonb_set(definition,'{card_description}',item->'card');
  end if;
  if item ? 'core_tools' then
   if prior.metadata->>'write_state_version' is distinct from '1' then raise exception 'phase_tools_requires_write_state'; end if;
   if definition->'core_tools' is distinct from item->'core_tools_before' then raise exception 'phase_tools_core_tools_changed'; end if;
   definition:=jsonb_set(jsonb_set(definition,'{core_tools}',item->'core_tools'),'{phase_tools}',item->'phase_tools');
  end if;
  select coalesce(max(version),0)+1 into next_version from shared.ai_prompt_versions where prompt_id=prior.prompt_id;
  insert into shared.ai_prompt_versions(prompt_id,version,definition_kind,definition_format_version,metadata,content,definition,flow,available_variables)
   values(prior.prompt_id,next_version,prior.definition_kind,prior.definition_format_version,
    -- A card-only edit keeps the prior publication name: earlier publications use it
    -- to recognise themselves, so a replay must not mistake this version for theirs.
    (prior.metadata-'seed_version'-'source_revision')||case when item ? 'card' then jsonb_build_object('card_publication','phase-tools-v1','phase_tools_version',1)
     else jsonb_build_object('publication','phase-tools-v1','phase_tools_version',1) end,
    prior.content,definition,prior.flow,prior.available_variables) returning id into version_uuid;
  activation:=activation||jsonb_build_object(item->>'key',version_uuid);
 end loop;
 if activation<>'{}'::jsonb then perform shared.activate_ai_catalog('bob',activation); end if;
end $phase_tools_publication$;
commit;
`
const target = process.argv.find(arg => arg.endsWith('_bob_phase_tools_catalog.sql'))
if (target) {
 if (process.argv.includes('--check')) { if (readFileSync(target, 'utf8') !== sql) throw Error('Phase tools publication is stale') }
 else writeFileSync(target, sql)
}
