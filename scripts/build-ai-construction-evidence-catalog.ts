import { readFileSync, writeFileSync } from 'node:fs'
import { CONSTRUCTION_EVIDENCE_CHECK_TOOL } from '../supabase/functions/_shared/construction-draft.ts'
import { CONSTRUCTION_EVIDENCE_VIEW_TOOL } from '../supabase/functions/_shared/construction-views.ts'

const spec=[CONSTRUCTION_EVIDENCE_CHECK_TOOL,CONSTRUCTION_EVIDENCE_VIEW_TOOL].map(({function:f})=>({key:'tools.'+f.name,
 patch:{description:f.description,parameters:f.parameters,required_parameters:f.parameters.required}}))
const sql=`-- Generated by scripts/build-ai-construction-evidence-catalog.ts.
-- Apply 20261027101807_construction_observations.sql, deploy compatible ask-bob
-- AND bob-worker, then activate. Old manifests retain their prior schemas/path.
begin;
set local lock_timeout='5s';
set local statement_timeout='60s';
do $construction_evidence_publication$
declare specs jsonb:=$construction_evidence_spec$${JSON.stringify(spec)}$construction_evidence_spec$::jsonb;
 item jsonb; prior shared.ai_prompt_versions; next_version integer; version_uuid uuid; activation jsonb:='{}';
begin
 perform pg_advisory_xact_lock(hashtextextended('ai_catalog:bob',0));
 for item in select value from jsonb_array_elements(specs) loop
  select v.* into prior from shared.ai_prompts p join shared.ai_prompt_versions v on v.id=p.active_version_id
   where p.app='bob' and p.prompt_key=item->>'key' and p.retired_at is null for update of p;
  if not found then raise exception 'construction_evidence_contract_missing'; end if;
  if prior.metadata->>'construction_evidence_version'='1' then continue; end if;
  select coalesce(max(version),0)+1 into next_version from shared.ai_prompt_versions where prompt_id=prior.prompt_id;
  insert into shared.ai_prompt_versions(prompt_id,version,definition_kind,definition_format_version,metadata,content,definition,flow,available_variables)
   values(prior.prompt_id,next_version,prior.definition_kind,prior.definition_format_version,
    (prior.metadata-'seed_version'-'source_revision')||jsonb_build_object('publication','construction-evidence-v1','construction_evidence_version',1),
    prior.content,prior.definition||(item->'patch'),prior.flow,prior.available_variables) returning id into version_uuid;
  activation:=activation||jsonb_build_object(item->>'key',version_uuid);
 end loop;
 if activation<>'{}'::jsonb then perform shared.activate_ai_catalog('bob',activation); end if;
end $construction_evidence_publication$;
commit;
`
const target=process.argv.find(arg=>arg.endsWith('_ai_construction_evidence_catalog.sql'))
if(!target)throw Error('Pass the *_ai_construction_evidence_catalog.sql migration path')
if(process.argv.includes('--check')){
 if(readFileSync(target,'utf8')!==sql)throw Error('Construction evidence catalog is stale')
}else writeFileSync(target,sql)
