const edits = [
  { key: 'bob.toolbox.intro-lazy', content: 'Your project toolbox\n\nThe directory shows available capabilities and prerequisites. describe_tool loads an exact tool name; its manual and schema appear in the next request and stay while you keep using it. A step without it releases it, and describe_tool loads it again when you need it. Workflow names select methods without loading their member schemas.' },
  { key: 'agent-contract.ask-bob', metadata: { notebook_version: 1 } },
]
const sql = `-- Generated by scripts/build-ai-notebook-catalog.ts.
-- Bob's per-job notebook and idle tool release for NEW durable main turns
-- (owner decision 2026-10-20). Deploy the runtimes reading notebook_version
-- first. Running jobs keep their pinned manifest and execution identity.
begin;
set local lock_timeout='5s';
set local statement_timeout='60s';
do $bob_notebook_publication$
declare additions jsonb:=$bob_notebook_additions$${JSON.stringify(additions, null, 2)}$bob_notebook_additions$::jsonb;
 edits jsonb:=$bob_notebook_edits$${JSON.stringify(edits, null, 2)}$bob_notebook_edits$::jsonb;
 patch jsonb; prior shared.ai_prompt_versions; prompt_uuid uuid; version_uuid uuid; next_version integer; activation jsonb:='{}';
begin
 perform pg_advisory_xact_lock(hashtextextended('ai_catalog:bob',0));
 if not exists(select 1 from shared.ai_prompts p join shared.ai_prompt_versions v on v.id=p.active_version_id where p.app='bob' and p.prompt_key='agent-contract.ask-bob' and v.metadata->'result_reference_version'='1'::jsonb) then raise exception 'notebook_result_references_required'; end if;
 for patch in select value from jsonb_array_elements(additions) loop
  if exists(select 1 from shared.ai_prompts where app='bob' and prompt_key=patch->>'key') then raise exception 'notebook_already_published: %',patch->>'key'; end if;
  insert into shared.ai_prompts(app,prompt_key,label,description,content,flow,definition_kind)
   values('bob',patch->>'key',patch->>'key','Bob notebook v1',coalesce(patch->>'content',''),'',patch->>'kind') returning id into prompt_uuid;
  insert into shared.ai_prompt_versions(prompt_id,version,definition_kind,definition_format_version,metadata,content,definition,flow,available_variables)
   values(prompt_uuid,1,patch->>'kind',1,jsonb_build_object('publication','${publication}'),coalesce(patch->>'content',''),coalesce(patch->'definition','{}'::jsonb),'','[]'::jsonb) returning id into version_uuid;
  activation:=activation||jsonb_build_object(patch->>'key',version_uuid);
 end loop;
 for patch in select value from jsonb_array_elements(edits) loop
  select v.* into prior from shared.ai_prompts p join shared.ai_prompt_versions v on v.id=p.active_version_id where p.app='bob' and p.prompt_key=patch->>'key' and p.retired_at is null for update of p;
  if not found then raise exception 'notebook_definition_missing: %',patch->>'key'; end if;
  if patch->'metadata' ? 'notebook_version' and prior.metadata ? 'notebook_version' then raise exception 'notebook_already_published: %',patch->>'key'; end if;
  select coalesce(max(version),0)+1 into next_version from shared.ai_prompt_versions where prompt_id=prior.prompt_id;
  insert into shared.ai_prompt_versions(prompt_id,version,definition_kind,definition_format_version,metadata,content,definition,flow,available_variables)
   values(prior.prompt_id,next_version,prior.definition_kind,prior.definition_format_version,(prior.metadata-'seed_version'-'source_revision')||jsonb_build_object('publication','${publication}')||coalesce(patch->'metadata','{}'::jsonb),coalesce(patch->>'content',prior.content),prior.definition,prior.flow,prior.available_variables) returning id into version_uuid;
  activation:=activation||jsonb_build_object(patch->>'key',version_uuid);
 end loop;
 perform shared.activate_ai_catalog('bob',activation);
end $bob_notebook_publication$;
commit;
`
const path = process.argv[2]
if (!path) throw new Error('Pass the migration path')
if (process.argv.includes('--check')) {
  if (readFileSync(path, 'utf8') !== sql) throw new Error('Notebook publication differs from source')
  console.log('Verified notebook publication.')
} else writeFileSync(path, sql)
