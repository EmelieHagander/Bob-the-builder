/** Owner decision 2026-10-29: an explicit request creates its Solution, records
 * its construction purpose and alignment, and selects it in one call. Publishes
 * one interface field, its manual text and continuations; no agent prompt,
 * model profile or role changes. Requires the write-state publication. */
import { readFileSync, writeFileSync } from 'node:fs'
import { CREATE_SELECT_PARAMETERS } from '../supabase/functions/_shared/project-solution-actions.ts'

export const CREATE_SELECT_MANUAL = 'select=true also selects the new alternative for scope_ref in the same call; use it when the owner asked for this solution. The saved result then reports selected, construction_readiness, creation_state and the selected edit entry; if the selection fails, the alternative stays saved and unselected and selection names why. select=false keeps the current selection and returns the solution_ref. For an explicitly specified construction, set /design_intent/summary first, then /design_intent/purpose "construction", then /design_intent/alignment {"status":"aligned","basis":...} only when the request itself states the needed choices; otherwise keep it draft and add the open choices.'
const SAVE_TOOLS = ['save_construction_draft', 'search_material_catalog', 'read_material_catalog']
const specs = [
 {key:'tools.create_solution_alternative',
  parameters:CREATE_SELECT_PARAMETERS,
  replacements:[
   ['Creating does not select the alternative. The saved result returns its solution_ref for select_solution_alternative with the same scope_ref.',CREATE_SELECT_MANUAL],
   ['Selection is separate.','select=true selects it in the same call.'],
  ]},
 {key:'bob.tools',replacements:[],
  add_followups:[
   {after_tool:'create_solution_alternative',statuses:['saved'],when:{field:'creation_state',equals:'ready'},tools:SAVE_TOOLS},
   {after_tool:'create_solution_alternative',statuses:['saved'],when:{field:'creation_state',equals:'needs_data'},tools:['edit_project_record']},
  ]},
]
const sql=`-- Generated by scripts/build-bob-create-select-catalog.ts.
-- Owner decision 2026-10-29: one create call may also select the new alternative.
-- Install both matching Edge runtimes before activation. Existing manifests remain pinned.
begin;
set local lock_timeout='5s';
set local statement_timeout='60s';
do $create_select_publication$
declare specs jsonb:=$create_select_spec$${JSON.stringify(specs)}$create_select_spec$::jsonb;
 item jsonb; prior shared.ai_prompt_versions; definition jsonb; replacement jsonb; field text; matched boolean;
 next_version integer; version_uuid uuid; activation jsonb:='{}';
begin
 perform pg_advisory_xact_lock(hashtextextended('ai_catalog:bob',0));
 for item in select value from jsonb_array_elements(specs) loop
  select v.* into prior from shared.ai_prompts p join shared.ai_prompt_versions v on v.id=p.active_version_id
   where p.app='bob' and p.prompt_key=item->>'key' and p.retired_at is null for update of p;
  if not found then raise exception 'create_select_contract_missing: %',item->>'key'; end if;
  if prior.metadata->>'create_select_version'='1' then continue; end if;
  if prior.metadata->>'write_state_version' is distinct from '1' then raise exception 'create_select_requires_write_state: %',item->>'key'; end if;
  definition:=prior.definition;
  -- Every replaced sentence must exist; a drifted text stops the publication.
  for replacement in select value from jsonb_array_elements(item->'replacements') loop
   matched:=false;
   foreach field in array array['description','additional_description','card_description'] loop
    if definition ? field and position(replacement->>0 in definition->>field)>0 then
     definition:=jsonb_set(definition,array[field],to_jsonb(replace(definition->>field,replacement->>0,replacement->>1)));matched:=true;
    end if;
   end loop;
   if not matched then raise exception 'create_select_text_missing: %',item->>'key'; end if;
  end loop;
  if item ? 'parameters' then
   definition:=definition||jsonb_build_object('parameters',item->'parameters','required_parameters',item#>'{parameters,required}');
  end if;
  if item ? 'add_followups' then
   definition:=jsonb_set(definition,'{operation_followups}',(definition->'operation_followups')||(item->'add_followups'));
  end if;
  select coalesce(max(version),0)+1 into next_version from shared.ai_prompt_versions where prompt_id=prior.prompt_id;
  insert into shared.ai_prompt_versions(prompt_id,version,definition_kind,definition_format_version,metadata,content,definition,flow,available_variables)
   values(prior.prompt_id,next_version,prior.definition_kind,prior.definition_format_version,
    (prior.metadata-'seed_version'-'source_revision')||jsonb_build_object('publication','create-select-v1','create_select_version',1),
    prior.content,definition,prior.flow,prior.available_variables) returning id into version_uuid;
  activation:=activation||jsonb_build_object(item->>'key',version_uuid);
 end loop;
 if activation<>'{}'::jsonb then perform shared.activate_ai_catalog('bob',activation); end if;
end $create_select_publication$;
commit;
`
const target=process.argv.find(arg=>arg.endsWith('_bob_create_select_catalog.sql'))
if(target){
 if(process.argv.includes('--check')){if(readFileSync(target,'utf8')!==sql)throw Error('Create-select publication is stale')}
 else writeFileSync(target,sql)
}else if(process.argv[1]?.endsWith('build-bob-create-select-catalog.ts'))throw Error('Pass the *_bob_create_select_catalog.sql migration path')
